#!/usr/bin/env python3
"""
Prepare dataset for MAGIC detector.

Converts PE .exe files to IDA-like .asm format using radare2 (r2),
and reorganizes data into MAGIC's expected flat directory layout.

Train sources: Adv_detector/ + Adv_agent/ (merged into TrainSet/)
Test source:   Test/ (→ TestSet/)
"""

import os
import re
import csv
import subprocess
import struct
from pathlib import Path
from concurrent.futures import ProcessPoolExecutor, as_completed
from typing import List, Tuple, Optional

# Binary classification: folder name -> 1-indexed label
# MAGIC internally does label = int(Class) - 1
# So Class=1 -> label=0 (Benign), Class=2 -> label=1 (Malware)
CLASS_MAP = {
    'Benign':     1,   # -> internal label 0 (benign)
    'Locker':     2,   # -> internal label 1 (malware)
    'Mediyes':    2,   # -> internal label 1 (malware)
    'Winwebsec':  2,   # -> internal label 1 (malware)
    'Zbot':       2,   # -> internal label 1 (malware)
    'Zeroaccess': 2,   # -> internal label 1 (malware)
}

# Multiple train input directories (merged into one TrainSet)
TRAIN_INPUT_DIRS = ['Adv_detector', 'Adv_agent']
TEST_INPUT_DIR = 'Test'

BASE_DIR = Path(__file__).parent.resolve()


def detect_pe_arch(exe_path: str) -> str:
    """Detect if PE is 32-bit or 64-bit by reading PE header."""
    try:
        with open(exe_path, 'rb') as f:
            dos_sig = f.read(2)
            if dos_sig != b'MZ':
                return 'unknown'
            f.seek(0x3C)
            pe_offset = struct.unpack('<I', f.read(4))[0]
            f.seek(pe_offset)
            pe_sig = f.read(4)
            if pe_sig != b'PE\x00\x00':
                return 'unknown'
            machine = struct.unpack('<H', f.read(2))[0]
            if machine == 0x14c:
                return 'x86'
            elif machine == 0x8664:
                return 'x86_64'
            else:
                return 'unknown'
    except Exception:
        return 'unknown'


# Create a helper script for angr once
ANGR_HELPER_PATH = os.path.join(BASE_DIR, 'angr_helper.py')
if not os.path.exists(ANGR_HELPER_PATH):
    with open(ANGR_HELPER_PATH, 'w') as f:
        f.write("""import sys, os
import angr, capstone

def disassemble(exe_path, output_path):
    try:
        proj = angr.Project(exe_path, load_options={'auto_load_libs': False})
        with open(output_path, 'w') as f:
            f.write('HEADER:00400000 ; Disassembly generated by angr\\n')
            f.write('HEADER:00400000\\n')
            for section in proj.loader.main_object.sections:
                if section.is_executable:
                    sec_name = section.name if section.name else ".text"
                    try:
                        sec_bytes = proj.loader.memory.load(section.vaddr, section.memsize)
                    except KeyError:
                        continue
                    md = capstone.Cs(proj.arch.cs_arch, proj.arch.cs_mode)
                    for i in md.disasm(sec_bytes, section.vaddr):
                        hex_addr = f"{i.address:08X}"
                        raw_bytes = i.bytes.hex().upper()
                        spaced_bytes = ' '.join(raw_bytes[j:j+2] for j in range(0, len(raw_bytes), 2))
                        f.write(f"{sec_name}:{hex_addr} {spaced_bytes}  {i.mnemonic} {i.op_str}\\n")
        sys.exit(0)
    except Exception as e:
        sys.exit(1)

if __name__ == '__main__':
    disassemble(sys.argv[1], sys.argv[2])
""")

def exe_to_ida_asm_angr(exe_path: str, asm_path: str) -> bool:
    """
    Convert a PE .exe to an IDA-like .asm format using angr.
    Runs the angr helper using the global python3 to bypass the venv.
    """
    try:
        arch = detect_pe_arch(exe_path)
        if arch == 'unknown':
            return False

        # Use current python executable which has angr installed
        import sys
        result = subprocess.run(
            [sys.executable, ANGR_HELPER_PATH, exe_path, asm_path],
            capture_output=True, text=True, timeout=180
        )

        return result.returncode == 0 and os.path.exists(asm_path)
    except Exception:
        return False


def get_binary_id(exe_path: str) -> str:
    """Generate a unique binary ID from the exe filename."""
    return Path(exe_path).stem


def process_one_file(args: Tuple[str, str, str, int]) -> Tuple[str, int, bool]:
    """Process a single exe file. Returns (binaryId, label, success)."""
    exe_path, output_dir, class_name, label = args
    binary_id = get_binary_id(exe_path)
    asm_path = os.path.join(output_dir, f'{binary_id}.asm')

    # Skip if already converted
    if os.path.exists(asm_path) and os.path.getsize(asm_path) > 100:
        return (binary_id, label, True)

    success = exe_to_ida_asm_angr(exe_path, asm_path)
    return (binary_id, label, success)


def collect_exe_files(input_dirs: List[str]) -> List[Tuple[str, str, int]]:
    """
    Collect all .exe files from multiple input directories.
    Returns list of (exe_path, class_name, label).
    Deduplicates by filename across directories.
    """
    seen_ids = set()
    tasks = []

    for input_dir in input_dirs:
        if not os.path.isdir(input_dir):
            print(f'  [WARN] Directory not found: {input_dir}')
            continue

        for class_name, label in sorted(CLASS_MAP.items()):
            class_dir = os.path.join(input_dir, class_name)
            if not os.path.isdir(class_dir):
                continue

            exe_files = sorted([
                os.path.join(class_dir, f)
                for f in os.listdir(class_dir)
                if f.lower().endswith('.exe')
            ])

            added = 0
            for exe_path in exe_files:
                bid = get_binary_id(exe_path)
                if bid not in seen_ids:
                    seen_ids.add(bid)
                    tasks.append((exe_path, class_name, label))
                    added += 1

            src = os.path.basename(input_dir)
            print(f'  [{src}] {class_name} (label={label}): {added} new files')

    return tasks


def process_dataset(input_dirs: List[str], output_dir: str,
                    max_workers: int = 4) -> List[Tuple[str, int]]:
    """Process all exe files from multiple input directories."""
    os.makedirs(output_dir, exist_ok=True)

    all_files = collect_exe_files(input_dirs)

    # Build tasks for ProcessPoolExecutor
    tasks = [
        (exe_path, output_dir, class_name, label)
        for (exe_path, class_name, label) in all_files
    ]

    results = []
    success_count = 0
    fail_count = 0
    fail_classes = {}

    print(f'\n  Processing {len(tasks)} files with {max_workers} workers...')
    with ProcessPoolExecutor(max_workers=max_workers) as executor:
        futures = {}
        for t in tasks:
            future = executor.submit(process_one_file, t)
            futures[future] = t

        for i, future in enumerate(as_completed(futures), 1):
            task_args = futures[future]
            binary_id, label, success = future.result()
            class_name = task_args[2]

            if success:
                results.append((binary_id, label))
                success_count += 1
            else:
                fail_count += 1
                fail_classes[class_name] = fail_classes.get(class_name, 0) + 1

            if i % 100 == 0 or i == len(tasks):
                print(f'  Progress: {i}/{len(tasks)} '
                      f'(success={success_count}, fail={fail_count})')

    if fail_classes:
        print(f'\n  Failed files by class:')
        for cls, cnt in sorted(fail_classes.items()):
            print(f'    {cls}: {cnt} failures')

    return results


def create_labels_csv(results: List[Tuple[str, int]], output_path: str):
    """Create labels CSV in MAGIC's expected format."""
    with open(output_path, 'w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['Id', 'Class'])
        for binary_id, label in sorted(results):
            writer.writerow([binary_id, label])
    print(f'  Wrote {len(results)} entries to {output_path}')


def main():
    import argparse
    parser = argparse.ArgumentParser(
        description='Convert PE exe files to IDA-like .asm for MAGIC (using radare2)')
    parser.add_argument('--workers', type=int, default=4,
                        help='Number of parallel workers')
    parser.add_argument('--train-output', type=str,
                        default=str(BASE_DIR / 'TrainSet'))
    parser.add_argument('--test-output', type=str,
                        default=str(BASE_DIR / 'TestSet'))
    args = parser.parse_args()

    # Build input paths
    train_input_dirs = [str(BASE_DIR / d) for d in TRAIN_INPUT_DIRS]
    test_input_dirs = [str(BASE_DIR / TEST_INPUT_DIR)]

    print('=' * 60)
    print('MAGIC Data Preparation Pipeline (radare2)')
    print('=' * 60)
    print(f'  Train sources: {TRAIN_INPUT_DIRS}')
    print(f'  Test source:   {TEST_INPUT_DIR}')

    # Process TrainSet (merge Adv_detector + Adv_agent)
    print(f'\n[1/3] Converting TrainSet from {len(train_input_dirs)} sources...')
    train_results = process_dataset(
        train_input_dirs, args.train_output,
        max_workers=args.workers
    )

    # Create trainLabels.csv
    print(f'\n[2/3] Creating trainLabels.csv')
    labels_path = str(BASE_DIR / 'trainLabels.csv')
    create_labels_csv(train_results, labels_path)

    # Process TestSet
    print(f'\n[3/3] Converting TestSet...')
    test_results = process_dataset(
        test_input_dirs, args.test_output,
        max_workers=args.workers
    )

    test_labels_path = str(BASE_DIR / 'testLabels.csv')
    create_labels_csv(test_results, test_labels_path)

    # Summary
    benign_train = sum(1 for _, l in train_results if l == 1)
    malware_train = sum(1 for _, l in train_results if l == 2)
    benign_test = sum(1 for _, l in test_results if l == 1)
    malware_test = sum(1 for _, l in test_results if l == 2)

    print('\n' + '=' * 60)
    print('Summary:')
    print(f'  TrainSet: {len(train_results)} files '
          f'(Benign={benign_train}, Malware={malware_train})')
    print(f'  TestSet:  {len(test_results)} files '
          f'(Benign={benign_test}, Malware={malware_test})')
    print(f'  Train labels: {labels_path}')
    print(f'  Test labels:  {test_labels_path}')
    print('=' * 60)


if __name__ == '__main__':
    main()
