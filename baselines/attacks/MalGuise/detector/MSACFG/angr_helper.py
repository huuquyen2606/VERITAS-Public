import sys, os
import angr, capstone

def disassemble(exe_path, output_path):
    try:
        proj = angr.Project(exe_path, load_options={'auto_load_libs': False})
        with open(output_path, 'w') as f:
            f.write('HEADER:00400000 ; Disassembly generated by angr\n')
            f.write('HEADER:00400000\n')
            for section in proj.loader.main_object.sections:
                if section.is_executable:
                    sec_name = section.name if section.name else ".text"
                    try:
                        sec_bytes = proj.loader.memory.load(section.vaddr, section.memsize)
                    except KeyError:
                        continue
                    md = capstone.Cs(proj.arch.cs_arch, proj.arch.cs_mode)
                    for i in md.disasm(sec_bytes, section.vaddr):
                        hex_addr = f"{i.address:08X}"
                        raw_bytes = i.bytes.hex().upper()
                        spaced_bytes = ' '.join(raw_bytes[j:j+2] for j in range(0, len(raw_bytes), 2))
                        f.write(f"{sec_name}:{hex_addr} {spaced_bytes}  {i.mnemonic} {i.op_str}\n")
        sys.exit(0)
    except Exception as e:
        sys.exit(1)

if __name__ == '__main__':
    disassemble(sys.argv[1], sys.argv[2])
